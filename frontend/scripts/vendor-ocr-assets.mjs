import { cp, mkdir, readdir, copyFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const modules = path.join(root, 'node_modules');
const output = path.join(root, 'public', 'ocr');

async function findFile(dir, predicate) {
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return null; }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isFile() && predicate(entry.name)) return full;
    if (entry.isDirectory()) {
      const found = await findFile(full, predicate);
      if (found) return found;
    }
  }
  return null;
}

async function copyCoreFiles() {
  const coreSource = path.join(modules, 'tesseract.js-core');
  const coreOutput = path.join(output, 'core');
  await mkdir(coreOutput, { recursive: true });
  const required = [
    'tesseract-core.wasm.js',
    'tesseract-core-simd.wasm.js',
    'tesseract-core-lstm.wasm.js',
    'tesseract-core-simd-lstm.wasm.js',
  ];
  for (const filename of required) {
    const file = await findFile(coreSource, (name) => name === filename);
    if (!file) throw new Error(`Missing ${filename} in tesseract.js-core. Re-run npm install.`);
    await copyFile(file, path.join(coreOutput, filename));
  }
  const wasmFiles = [];
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (/\.wasm$/i.test(entry.name)) wasmFiles.push(full);
    }
  }
  await walk(coreSource);
  for (const source of wasmFiles) await copyFile(source, path.join(coreOutput, path.basename(source)));
}

async function main() {
  await mkdir(output, { recursive: true });
  const worker = path.join(modules, 'tesseract.js', 'dist', 'worker.min.js');
  try { await copyFile(worker, path.join(output, 'worker.min.js')); }
  catch { throw new Error('Could not find tesseract.js/dist/worker.min.js. Check the pinned tesseract.js version.'); }
  await copyCoreFiles();
  const languageOut = path.join(output, 'lang');
  await mkdir(languageOut, { recursive: true });
  for (const language of ['eng', 'hin', 'tel']) {
    const langRoot = path.join(modules, '@tesseract.js-data', language);
    const traineddata = await findFile(langRoot, (name) => name === `${language}.traineddata.gz`);
    if (!traineddata) throw new Error(`Could not find ${language}.traineddata.gz in @tesseract.js-data/${language}.`);
    await copyFile(traineddata, path.join(languageOut, `${language}.traineddata.gz`));
  }
  await writeFile(path.join(output, 'ASSETS.md'), `# Locally hosted OCR assets\n\nGenerated by npm postinstall from pinned packages. The application loads Tesseract assets from /ocr and does not fall back to a CDN.\n\nIncluded languages: English (eng), Hindi (hin), Telugu (tel).\n`, 'utf8');
  console.log('HerNest OCR assets copied to public/ocr (worker, core, English, Hindi, Telugu).');
}

main().catch((error) => {
  console.error(`[HerNest OCR assets] ${error.message}`);
  process.exitCode = 1;
});
